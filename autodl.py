HOME = Path.home()
ROOT = Path(__file__).resolve().parent
BASE = Path(os.environ.get('AUTODL_CONFIG_DIR', str(HOME / '.config/autodl'))).expanduser().resolve()
REGISTRY = BASE / 'instances.json'
CACHE = BASE / 'status.json'
SSH_DIR = HOME / '.ssh' if BASE == HOME / '.config/autodl' else BASE / 'ssh'
KEY = SSH_DIR / 'id_autodl_ed25519'
SSH_CONFIG = SSH_DIR / 'autodl.conf'
KNOWN = SSH_DIR / 'known_hosts'
_REGISTRY_LOCK = threading.RLock()
_KEY_LOCK = threading.Lock()
PROBE = '''printf '__AUTODL_OK__\\n'
if command -v nvidia-smi >/dev/null 2>&1; then
  nvidia-smi --query-gpu=index,name,memory.total,memory.used,memory.free,utilization.gpu --format=csv,noheader,nounits
else
  printf '__NO_NVIDIA_SMI__\\n'
fi'''

def atomic_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as f:
            json.dump(value, f, ensure_ascii=False, indent=2)
            f.write('\n')
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)

def read_json(path, default):
    try:
        return json.loads(path.read_text())
    except FileNotFoundError:
        return default

def load():
    return validate_registry(read_json(REGISTRY, {'next_id': 1, 'instances': []}))

def identity_path(item):
    return Path(item.get('identity_file') or KEY).expanduser().resolve()

def public_key_path(key):
    return Path(str(key) + '.pub')

def validate_item(item):
    if not isinstance(item, dict):
        raise ValueError('实例配置需为 JSON 对象')
    if set(item) - {'id', 'name', 'region', 'host', 'port', 'user', 'identity_file'}:
        raise ValueError('实例配置包含未知字段；请勿保存密码')
    if type(item.get('id')) is not int or item['id'] < 1:
        raise ValueError('实例编号必须为正整数')
    if not isinstance(item.get('name'), str) or not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}', item['name']):
        raise ValueError('别名请使用英文字母、数字、短横线或下划线')
    if not isinstance(item.get('host'), str) or not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9.-]{0,252}', item['host']):
        raise ValueError('SSH 主机地址无效')
    if not isinstance(item.get('user'), str) or not re.fullmatch(r'[a-zA-Z0-9_][a-zA-Z0-9_.-]{0,63}', item['user']):
        raise ValueError('SSH 用户名无效')
    if type(item.get('port')) is not int or not 1 <= item['port'] <= 65535:
        raise ValueError('SSH 端口需为 1–65535')
    region = item.get('region')
    if not isinstance(region, str) or not region.strip() or len(region) > 80 or any(ord(c) < 32 or ord(c) == 127 for c in region):
        raise ValueError('区域名称需为 1–80 个可见字符')
    key = item.get('identity_file', '')
    if not isinstance(key, str) or any(ord(c) < 32 or ord(c) == 127 or c in '\"%' for c in key):
        raise ValueError('密钥文件路径无效')
    return item

def validate_registry(data):
    if not isinstance(data, dict) or set(data) != {'next_id', 'instances'} or not isinstance(data['instances'], list):
        raise ValueError('实例清单格式无效，请检查 instances.json')
    seen_id, seen_name, seen_address = set(), set(), set()
    for item in data['instances']:
        validate_item(item)
        address = (item['user'], item['host'].lower(), item['port'])
        if item['id'] in seen_id or item['name'] in seen_name or address in seen_address:
            raise ValueError('实例清单存在重复编号、别名或 SSH 地址')
        seen_id.add(item['id']); seen_name.add(item['name']); seen_address.add(address)
    if type(data['next_id']) is not int or data['next_id'] <= max(seen_id, default=0):
        raise ValueError('next_id 必须大于所有已有实例编号')
    return data

@contextmanager
def registry_lock():
    BASE.mkdir(parents=True, exist_ok=True)
    with _REGISTRY_LOCK:
        fd = os.open(BASE / '.instances.lock', os.O_CREAT | os.O_RDWR, 0o600)
        with os.fdopen(fd, 'a') as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            try:
                yield
            finally:
                fcntl.flock(lock, fcntl.LOCK_UN)

def alias(item):
    return 'ad-' + item['name']

def sync_config(data):
    validate_registry(data)
    SSH_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)
    lines = ['# Generated by autodl. Edit instances via autodl add/remove/rename.']
    for i in data['instances']:
        lines.extend([
            f"Host {alias(i)}", f"    HostName {i['host']}",
            f"    Port {i['port']}", f"    User {i['user']}",
            f'    IdentityFile "{identity_path(i)}"', '    IdentitiesOnly yes',
            f'    UserKnownHostsFile "{KNOWN}"',
            '    StrictHostKeyChecking accept-new', '    ConnectTimeout 8',
            '    ConnectionAttempts 1', '    ServerAliveInterval 30',
            '    ServerAliveCountMax 3', '',
        ])
    fd, temporary = tempfile.mkstemp(dir=SSH_DIR)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write('\n'.join(lines) + '\n')
        os.replace(temporary, SSH_CONFIG)
    finally:
        if os.path.exists(temporary): os.unlink(temporary)

def save(data):
    validate_registry(data)
    atomic_json(REGISTRY, data)
    sync_config(data)

def ssh_args(i, batch=True):
    validate_item(i)
    KNOWN.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    # Isolate launcher connections from unrelated Host * / ProxyJump settings.
    args = [shutil.which('ssh') or 'ssh', '-F', os.devnull, '-i', str(identity_path(i)),
            '-o', 'IdentitiesOnly=yes', '-o', 'StrictHostKeyChecking=accept-new',
            '-o', f'UserKnownHostsFile={KNOWN}', '-o', 'ConnectTimeout=8',
            '-o', 'ConnectionAttempts=1', '-o', 'ServerAliveInterval=30',
            '-o', 'ServerAliveCountMax=3', '-o', 'LogLevel=ERROR',
            '-p', str(i['port'])]
    if batch:
        args += ['-o', 'BatchMode=yes']
    return args + [f"{i['user']}@{i['host']}"]

def classify(error):
    e = error.lower()
    if 'host key verification failed' in e or 'host identification has changed' in e:
        return '主机指纹变更（需核实）'
    if 'permission denied' in e:
        return '需要配置密钥'
    if 'refused' in e:
        return '连接被拒绝'
    if 'resolve' in e:
        return '域名解析失败'
    return '无法连接（关机/释放/网络）'

def number(s):
    try:
        return float(s.strip())
    except ValueError:
        return None

def parse_gpus(output):
    gpus = []
    for row in csv.reader(io.StringIO(output)):
        if len(row) != 6 or not row[0].strip().isdigit():
            continue
        gpus.append(dict(zip(['index', 'name', 'total', 'used', 'free', 'util'],
                            [row[0].strip(), row[1].strip()] + [number(x) for x in row[2:]])))
    return gpus

def probe(i):
    stamp = dt.datetime.now().astimezone().isoformat(timespec='seconds')
    try:
        p = subprocess.run(ssh_args(i) + [PROBE], stdin=subprocess.DEVNULL,
                           capture_output=True, text=True, timeout=15)
        online = '__AUTODL_OK__' in p.stdout
        gpus = parse_gpus(p.stdout)
        return {'online': online, 'checked': stamp, 'gpus': gpus,
                'status': '在线' if online else classify(p.stderr),
                'gpu_error': ('未检测到 nvidia-smi' if '__NO_NVIDIA_SMI__' in p.stdout
                              else 'GPU 查询失败或不可见') if online and not gpus else '',
                'error': p.stderr.strip()[:1200]}
    except subprocess.TimeoutExpired:
        return {'online': False, 'checked': stamp, 'gpus': [], 'status': '连接超时'}

def refresh(items):
    previous = read_json(CACHE, {})
    with concurrent.futures.ThreadPoolExecutor(max_workers=min(8, max(1, len(items)))) as pool:
        results = list(pool.map(probe, items))
    for i, s in zip(items, results):
        old = previous.get(str(i['id']), {})
        if not s['online']:
            s['last_gpus'] = old.get('gpus') or old.get('last_gpus', [])
        previous[str(i['id'])] = s
    atomic_json(CACHE, previous)
    return previous

def is_idle(g):
    return g['used'] is not None and g['util'] is not None and g['used'] < 512 and g['util'] < 5

def width(s):
    return sum(2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s)

def pad(s, n):
    return s + ' ' * max(1, n - width(s))

def gib(n):
    return '?' if n is None else f'{n / 1024:.1f}'

def show(items, states, only_free=False, detailed=False):
    print('\nAutoDL 实例  ·  ' + dt.datetime.now().strftime('%m-%d %H:%M:%S'))
    if not items:
        print('暂无实例，使用 autodl add 添加。')
        return
    online = [states.get(str(i['id']), {}) for i in items if states.get(str(i['id']), {}).get('online')]
    all_gpus = [g for s in online for g in s.get('gpus', [])]
    print(f"在线 {len(online)}/{len(items)} 台  ·  GPU {len(all_gpus)} 张  ·  低占用 {sum(is_idle(g) for g in all_gpus)} 张")
    if only_free and not any(is_idle(g) for g in all_gpus):
        print('当前没有满足低占用阈值的 GPU。')
    for region in sorted({i['region'] for i in items}):
        group = [i for i in items if i['region'] == region]
        print(f'\n┌─ {region.upper()} ──────────────────────────────────────────')
        for i in group:
            s = states.get(str(i['id']), {})
            gpus = s.get('gpus', []) if s.get('online') else []
            idle = [g for g in gpus if is_idle(g)]
            if only_free and not idle:
                continue
            tag = f"{len(idle)}/{len(gpus)} 卡低占用" if gpus else ''
            models = Counter(g['name'].replace('NVIDIA GeForce ', '').replace('NVIDIA ', '') for g in gpus)
            model_text = ', '.join(f'{name} ×{count}' for name, count in models.items())
            print(f"│ [{i['id']}] {pad(i['name'], 14)} {s.get('status', '未检测')}  {model_text}  {tag}")
            if detailed:
                print(f"│     {i['user']}@{i['host']}:{i['port']}")
            elif gpus:
                metrics = '  '.join(f"{g['index']}:{gib(g['free'])}G/{'?' if g['util'] is None else format(g['util'], '.0f')}%" for g in gpus)
                print('│     GPU→剩余显存/利用率  ' + metrics)
            for g in gpus if detailed else []:
                label = '低占用' if is_idle(g) else '占用中/未知'
                util = '?' if g['util'] is None else f"{g['util']:.0f}%"
                name = g['name'].replace('NVIDIA GeForce ', '').replace('NVIDIA ', '')
                print(f"│     GPU {g['index']}  {pad(name, 19)} 空闲 {gib(g['free'])}/{gib(g['total'])} GiB  利用率 {pad(util, 5)} {label}")
            if s.get('gpu_error'):
                print('│     ' + s['gpu_error'])
            if not s.get('online') and s.get('last_gpus'):
                print('│     历史配置（非实时）：' + ', '.join(g['name'] for g in s['last_gpus']))
        print('└───────────────────────────────────────────────────────────')
    print('\n低占用参考：显存使用 <512 MiB 且利用率 <5%；瞬时采样，不代表 GPU 已预留。')

def resolve(data, token):
    items = data['instances']
    for i in items:
        if str(i['id']) == token or i['name'] == token or alias(i) == token:
            return i
    matches = [i for i in items if str(i['port']) == token]
    if len(matches) == 1:
        return matches[0]
    raise ValueError(f'实例未找到或端口不唯一：{token}。运行 autodl list 查看编号。')

def connect(i, command=None):
    atomic_json(BASE / 'last.json', {'id': i['id']})
    print(f"连接 {i['name']} ({i['host']}:{i['port']})", flush=True)
    args = ssh_args(i)
    if command:
        args.append(shlex.join(command))
    return subprocess.call(args)

def ensure_key():
    with _KEY_LOCK:
        SSH_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)
        if not KEY.exists():
            executable = shutil.which('ssh-keygen')
            if not executable:
                raise ValueError('未找到 ssh-keygen，请先安装 OpenSSH')
            subprocess.run([executable, '-q', '-t', 'ed25519', '-N', '',
                            '-C', 'autodl-local-access', '-f', str(KEY)],
                           check=True, capture_output=True, timeout=15)
        if not public_key_path(KEY).exists():
            raise ValueError('公钥文件缺失，请恢复同名 .pub 文件或选择其他 SSH 密钥')
    return public_key_path(KEY).read_text().strip()

def install_key(i, password=None):
    validate_item(i)
    key = identity_path(i)
    if key == KEY:
        ensure_key()
    elif not key.is_file():
        raise ValueError('指定的 SSH 私钥文件不存在')
    check = subprocess.run(ssh_args(i) + ['true'], stdin=subprocess.DEVNULL,
                           capture_output=True, text=True, timeout=15)
    if check.returncode == 0:
        return True
    if '主机指纹' in classify(check.stderr):
        raise ValueError('服务器指纹发生变化，请核实实例身份后再处理 known_hosts。')
    if 'permission denied' not in check.stderr.lower():
        raise ValueError('SSH 连接未成功：' + classify(check.stderr))
    executable = shutil.which('expect')
    if not executable:
        raise ValueError('密码配置免密需要 expect。macOS 可运行 brew install expect；Linux 可安装 expect，或将 autodl pubkey 输出添加至服务器 ~/.ssh/authorized_keys')
    if password is None:
        password = getpass.getpass(f"{i['name']} 的 SSH 密码（不会保存）: ")
    if not isinstance(password, str) or not password or len(password) > 1024 or '\n' in password or '\r' in password:
        raise ValueError('SSH 密码不能为空或包含换行')
    if not public_key_path(key).is_file():
        raise ValueError('公钥文件缺失，请提供与私钥同名的 .pub 文件')
    pub = public_key_path(key).read_text().strip()
    remote = ('umask 077; mkdir -p ~/.ssh && chmod 700 ~/.ssh && '
              'touch ~/.ssh/authorized_keys && chmod 600 ~/.ssh/authorized_keys && '
              f'(grep -qxF -- {shlex.quote(pub)} ~/.ssh/authorized_keys || '
              f'printf "\\n%s\\n" {shlex.quote(pub)} >> ~/.ssh/authorized_keys)')
    # Password travels through an anonymous stdin pipe, never argv/env/a file.
    args = ssh_args(i, batch=False)
    args[1:1] = ['-o', 'PreferredAuthentications=password,keyboard-interactive',
                 '-o', 'PubkeyAuthentication=no', '-o', 'NumberOfPasswordPrompts=1']
    p = subprocess.run([executable, str(ROOT / 'install-key.exp')] + args + [remote],
                       input=password + '\n', capture_output=True, text=True, timeout=35)
    if p.returncode:
        raise ValueError(f"{i['name']} 密钥安装失败（退出码 {p.returncode}）；请检查实例运行状态和密码。")
    verify = subprocess.run(ssh_args(i) + ['true'], stdin=subprocess.DEVNULL,
                            capture_output=True, text=True, timeout=15)
    if verify.returncode:
        raise ValueError(f"{i['name']} 密钥登录验证失败：{classify(verify.stderr)}")
    return True

def parse_ssh(command):
    if not isinstance(command, str) or not command.strip() or len(command) > 2048 or '\n' in command or '\r' in command:
        raise ValueError('请提供单行 SSH 命令（不含密码）')
    words = shlex.split(command)
    if words and words[0] == 'ssh':
        words.pop(0)
    port, target = 22, None
    while words:
        w = words.pop(0)
        if w == '-p' and words:
            port = int(words.pop(0))
        elif w.startswith('-p') and len(w) > 2:
            port = int(w[2:])
        elif re.fullmatch(r'[a-zA-Z0-9_.-]+@[a-zA-Z0-9.-]+', w) and target is None:
            target = w
        else:
            raise ValueError('只粘贴 ssh -p 端口 用户@地址；密码将在下一步隐藏输入。')
    if target is None or not 1 <= port <= 65535:
        raise ValueError('SSH 地址或端口无效。')
    user, host = target.split('@')
    return user, host, port

def create_instance(command, name='', region='', identity_file=''):
    if not all(isinstance(value, str) for value in (name, region, identity_file)):
        raise ValueError('别名、区域和密钥路径需为文字')
    user, host, port = parse_ssh(command)
    host = host.lower()
    region = region or (host.split('.')[1] if host.startswith('connect.') else 'other')
    name = name or f'{region}-{port}'
    if not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}', name):
        if name == f'{region}-{port}': name = f'instance-{port}'
    with registry_lock():
        data = load()
        for existing in data['instances']:
            if (existing['host'].lower(), existing['port'], existing['user']) == (host, port, user):
                raise ValueError(f"该 SSH 地址已存在：[{existing['id']}] {existing['name']}")
        item = dict(id=data['next_id'], name=name, region=region, host=host, port=port, user=user)
        if identity_file:
            if not isinstance(identity_file, str): raise ValueError('密钥路径无效')
            item['identity_file'] = str(Path(identity_file).expanduser().resolve())
            if not Path(item['identity_file']).is_file():
                raise ValueError('指定的 SSH 私钥文件不存在')
        validate_item(item)
        data['next_id'] += 1
        data['instances'].append(item)
        save(data)
    return item

def add(data, command=None, name=None, region=None, identity_file=''):
    i = create_instance(command or input('粘贴 SSH 命令（不含密码）: ').strip(), name or '', region or '', identity_file)
    data.clear(); data.update(load())
    name = i['name']
    print(f"已添加 [{i['id']}] {name}，开始配置免密登录。")
    install_key(i)
    print(f"免密登录验证成功：autodl {i['id']}")

def remove_instance(token):
    with registry_lock():
        data = load()
        item = resolve(data, str(token))
        data['instances'].remove(item)
        save(data)
    return item

def remove(data, token):
    i = remove_instance(token)
    data.clear(); data.update(load())
    print(f"已从本地列表移除 {i['name']}；云端实例和文件未做修改。")

def menu(data, region=None):
    while True:
        data = load()
        items = [i for i in data['instances'] if region is None or i['region'].lower() == region.lower()]
        if sys.stdin.isatty():
            print('正在并发查询 GPU 状态…', flush=True)
        show(items, refresh(items))
        if not sys.stdin.isatty():
            return 0
        print('\n输入 编号 / 端口 / 别名 → 连接  |  r 刷新  a 添加  d 编号 移除  q 退出')
        try:
            choice = input('autodl ❯ ').strip()
            if choice.lower() in ('q', 'quit', 'exit'):
                return 0
            if choice in ('', 'r'):
                continue
            if choice == 'a':
                add(data)
            elif choice.startswith('d '):
                remove(data, choice[2:].strip())
            else:
                rc = connect(resolve(data, choice))
                if rc:
                    print(f'SSH 退出码 {rc}；需要重装密钥时使用 autodl key 编号。')
                input('连接结束，按回车返回列表…')
        except (ValueError, subprocess.TimeoutExpired) as e:
            print('提示：', e)
            input('按回车继续…')

